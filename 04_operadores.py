# Operadores

'''
Operadores Aritméticos
+  (Suma)
-  (Resta)
*  (Multiplicación)
/  (División)
%  (Módulo)
** (Potenciación)
'''

valor1 = 10
valor2 = 3
suma = valor1 + valor2
resta = valor1 - valor2
multiplicacion = valor1 * valor2
division = valor1 / valor2
modulo = valor1 % valor2
potencia = valor1 ** valor2

print("Suma:", suma)
print("Resta:", resta)
print("Multiplicación:", multiplicacion)
print("División:", division)
print("Módulo:", modulo)
print("Potencia:", potencia)

